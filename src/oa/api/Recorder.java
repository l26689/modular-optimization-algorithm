package oa.api;

/**
 * 算法记录员，负责记录优化过程中算法找到的每一个解及其目标值。
 * <p>
 * 本抽象类定义了记录的通用契约：具体的记录策略（写入文件、存入内存列表、
 * 实时打印、推送至外部系统等）由子类实现。框架不关心记录格式和存储位置，
 * 仅保证在适当的时机调用 {@link #record(Object, Object)}。
 *
 * <h3>记录时机</h3>
 * 记录的具体时机由调用方（具体的优化算法）决定，而非本类约束。
 * 例如：
 * <ul>
 *   <li>模拟退火（SA）中，仅<b>被接受的解</b>才会被记录
 *       （由 {@code SimulatedAnnealing} 在其文档中声明此约定）。</li>
 *   <li>其他算法（如遗传算法）可能选择记录每一代的最优个体或整个种群。</li>
 * </ul>
 * 调用方应在各自的文档中明确声明其记录策略，Recorder 的实现类不应依赖
 * 特定的调用时机假设。
 *
 * <h3>实现要求</h3>
 * <ul>
 *   <li>{@code record} 应快速返回，避免阻塞主优化循环。
 *       若涉及 I/O 等耗时操作，建议在子类中使用异步或缓冲机制。</li>
 *   <li>传入的 {@code x} 和 {@code y} 为只读引用，实现类不应修改它们。</li>
 * </ul>
 *
 * <h3>获取优化结果</h3>
 * 由于 {@code solve()} 方法不再返回优化结果（返回类型为 {@code void}），
 * {@code Recorder} 的子类承担了<b>对外提供优化结果</b>的职责。
 * 子类应至少提供以下能力之一：
 * <ul>
 *   <li>获取历史最优解及其目标值（如 {@code getBestX()}、{@code getBestY()}）</li>
 *   <li>获取完整搜索历史（如 {@code getHistory()}，返回所有被记录的解）</li>
 *   <li>获取当前解（如 {@code getCurrentX()}，用于实时监控搜索进度）</li>
 * </ul>
 * 具体方法签名由子类自行定义，本抽象类不强制统一接口——不同应用场景
 * 对"结果"的定义差异很大（单目标只需最优值，多目标需要 Pareto 前沿，
 * 调试场景需要完整轨迹），一刀切的抽象反而会限制灵活性。
 *
 * @param <X> 解的表示类型
 * @param <Y> 目标函数返回值的类型
 * @param <Prob> 优化问题的类型，必须是 {@link Problem<X,Y>} 类的子类
 */
abstract public interface Recorder<X,Y,Prob extends Problem<X,Y>> {
    /**
     * 记录一个解及其对应的目标值。
     * <p>
     * 本方法被优化算法在适当的时机调用，调用频率由具体算法决定。
     * 实现类应将传入数据以合适的方式持久化或展示。

     * @param x 被记录的解（只读，不可修改）
     */
    abstract public void record(X x);
}