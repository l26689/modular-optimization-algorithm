package oa.api;

/**
 * 可复用的统一契约，表示组件支持重置其内部状态以重新参与优化。
 * <p>
 * 在模块化优化框架中，同一组件实例可能被用于多次独立的优化运行
 * （例如不同参数配置的对比实验、重复求解以统计均值方差等）。
 * 若组件在运行期间积累了内部状态（如迭代计数器、滑动窗口、自适应步长等），
 * 直接复用会导致状态污染，使后续运行结果不可靠。
 *
 * <h3>设计意图</h3>
 * 实现本接口的组件承诺：调用 {@link #reset()} 后，组件将回到与首次构造后
 * 等价的状态，可以安全地投入新一轮优化，而无需重新创建实例。
 * 这避免了反复创建/销毁对象的开销，同时保证了每次运行的独立性。
 *
 * <h3>适用范围</h3>
 * 本接口适用于所有维护可变内部状态的组件，典型包括：
 * <ul>
 *   <li>终止条件（内部迭代计数器）</li>
 *   <li>自适应扰动器（历史接受率滑动窗口）</li>
 *   <li>冷却策略（阶段计数器、自适应参数）</li>
 *   <li>Recorder（内部缓存列表）</li>
 * </ul>
 * 无状态的组件（如纯函数式冷却策略）也应实现本接口——
 * 对它们而言，{@code reset()} 是空操作，但实现本接口是对框架的统一承诺：
 * "该组件可安全复用"。这使外部调用者无需区分有状态与无状态组件，
 * 可以统一地在每次运行前调用 {@code reset()} 而无需条件判断。
 *
 * <h3>与 {@code init} 的区别</h3>
 * {@code reset()} 将组件恢复到初始状态，但不重新绑定问题实例。
 * 如果需要在不同问题之间切换，应重新构造组件实例并调用 {@code init}，
 * 而非仅依赖 {@code reset}。
 *
 * @see oa.core.Recorder
 * @see sa.core.SATerminationCondition
 */
public interface Reusable {
    /**
     * 将组件重置为初始状态，使其可以安全地参与新一轮优化运行。
     * <p>
     * 调用时机：由外部框架或用户在新一轮 {@code solve()} 调用之前手动触发。
     * 实现应清除所有累积的内部状态（计数器、历史记录、自适应参数等），
     * 使组件回到与首次构造后等价的状态。
     */
    void reset();
}